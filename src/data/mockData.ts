/**
 * Projects real GPS Latitude & Longitude to India SVG coordinates.
 * Bounds: Lat 7.8° to 37.0° N, Lng 68.0° to 97.5° E
 */
export function projectLatLngToIndiaMap(lat: number, lng: number, width = 1000, height = 900) {
  const minLat = 7.8;
  const maxLat = 37.2;
  const minLng = 68.2;
  const maxLng = 97.4;

  const padX = 75;
  const padY = 55;

  const clampedLng = Math.min(maxLng, Math.max(minLng, lng));
  const clampedLat = Math.min(maxLat, Math.max(minLat, lat));

  const x = padX + ((clampedLng - minLng) / (maxLng - minLng)) * (width - 2 * padX);
  const y = padY + ((maxLat - clampedLat) / (maxLat - minLat)) * (height - 2 * padY);

  const normX = Math.round(((x / width) * 100) * 10) / 10;
  const normY = Math.round(((y / height) * 100) * 10) / 10;

  return { x: normX, y: normY, pixelX: Math.round(x), pixelY: Math.round(y) };
}

